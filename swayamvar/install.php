{
    header('Content-Type: text/html; charset=UTF-8');
    ?>
    <!DOCTYPE html>
    <html lang="en">
    <head>
        <meta charset="UTF-8">
        <meta name="viewport" content="width=device-width, initial-scale=1.0">
        <title>Installation Error — Ramayan CMS</title>
        <link href="https://fonts.googleapis.com/css2?family=Inter:wght@400;500;600&display=swap" rel="stylesheet">
        <style>
            *,*::before,*::after{box-sizing:border-box;margin:0;padding:0}
            body{font-family:'Inter',sans-serif;background:#1A0A2E;color:#E2E8F0;min-height:100vh;display:flex;align-items:center;justify-content:center;padding:2rem}
            .wrap{max-width:500px;width:100%;text-align:center}
            .icon{font-size:3rem;margin-bottom:1rem}
            h1{color:#EF4444;font-size:1.5rem;margin-bottom:1rem}
            .errors{background:rgba(239,68,68,0.12);border:1px solid rgba(239,68,68,0.3);border-radius:10px;padding:1rem 1.25rem;text-align:left;margin-bottom:1.5rem}
            .errors li{color:#FCA5A5;font-size:.875rem;line-height:1.6;padding:.25rem 0}
            .errors li:not(:last-child){border-bottom:1px solid rgba(239,68,68,0.15)}
            a{display:inline-block;padding:.75rem 1.5rem;background:linear-gradient(135deg,#FF6B2B,#F5A623);color:#1A0A2E;font-weight:600;border-radius:8px;text-decoration:none;margin-top:.5rem}
        </style>
    </head>
    <body>
    <div class="wrap">
        <div class="icon">⚠️</div>
        <h1>Installation Error</h1>
        <ul class="errors">
            <?php foreach ($ramVar_errors as $ramVar_err): ?>
                <li><?= htmlspecialchars($ramVar_err, ENT_QUOTES, 'UTF-8') ?></li>
            <?php endforeach; ?>
        </ul>
        <a href="index.php">← Go Back and Try Again</a>
    </div>
    </body>
    </html>
    <?php
}
