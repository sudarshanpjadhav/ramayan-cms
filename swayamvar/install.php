 */

declare(strict_types=1);

// ── Security: block if already installed ─────────────────────────────────────
$ramVar_root       = dirname(__DIR__);
$ramVar_configFile = $ramVar_root . '/ramayan-config.php';

if (file_exists($ramVar_configFile)) {
    header('Location: ../index.php');
    exit;
}

// ── Only accept POST ──────────────────────────────────────────────────────────
if ($_SERVER['REQUEST_METHOD'] !== 'POST') {
    header('Location: index.php');
    exit;
}

// ── Collect & validate input ──────────────────────────────────────────────────
$ramVar_errors = [];

$ramVar_dbHost      = trim($_POST['db_host']         ?? 'localhost');
$ramVar_dbName      = trim($_POST['db_name']          ?? '');
$ramVar_dbUser      = trim($_POST['db_user']          ?? '');
$ramVar_dbPass      = $_POST['db_password']            ?? '';
$ramVar_dbPrefix    = preg_replace('/[^a-zA-Z0-9_]/', '', trim($_POST['db_prefix'] ?? 'ram_'));
$ramVar_siteName    = trim($_POST['site_name']         ?? '');
$ramVar_siteUrl     = rtrim(trim($_POST['site_url']   ?? ''), '/');
$ramVar_adminUser   = trim($_POST['admin_username']    ?? 'admin');
$ramVar_adminEmail  = trim($_POST['admin_email']       ?? '');
$ramVar_adminPass   = $_POST['admin_password']         ?? '';

// Validate
if ($ramVar_dbName === '')               $ramVar_errors[] = 'Database name is required.';
if ($ramVar_dbUser === '')               $ramVar_errors[] = 'Database user is required.';
if ($ramVar_dbPrefix === '')             $ramVar_dbPrefix = 'ram_';
if ($ramVar_siteName === '')             $ramVar_errors[] = 'Site name is required.';
if ($ramVar_siteUrl === '')              $ramVar_errors[] = 'Site URL is required.';
if ($ramVar_adminUser === '')            $ramVar_errors[] = 'Admin username is required.';
if (!filter_var($ramVar_adminEmail, FILTER_VALIDATE_EMAIL)) $ramVar_errors[] = 'Admin email is invalid.';
if (strlen($ramVar_adminPass) < 8)       $ramVar_errors[] = 'Admin password must be at least 8 characters.';

if (!empty($ramVar_errors)) {
    ramFn_installer_showError($ramVar_errors);
    exit;
}

// ── Test DB connection ────────────────────────────────────────────────────────
try {
    $ramVar_dsn = "mysql:host={$ramVar_dbHost};dbname={$ramVar_dbName};charset=utf8mb4";
    $ramVar_pdo = new PDO($ramVar_dsn, $ramVar_dbUser, $ramVar_dbPass, [
        PDO::ATTR_ERRMODE            => PDO::ERRMODE_EXCEPTION,
        PDO::ATTR_DEFAULT_FETCH_MODE => PDO::FETCH_ASSOC,
        PDO::ATTR_EMULATE_PREPARES   => false,
    ]);
} catch (PDOException $ramVar_e) {
    ramFn_installer_showError(['Cannot connect to database: ' . $ramVar_e->getMessage()]);
    exit;
}

// ── Generate security keys ────────────────────────────────────────────────────
function ramFn_installer_generateKey(): string
{
    return bin2hex(random_bytes(32));
}

$ramVar_authKey        = ramFn_installer_generateKey();
$ramVar_secureAuthKey  = ramFn_installer_generateKey();
$ramVar_loggedInKey    = ramFn_installer_generateKey();
$ramVar_nonceKey       = ramFn_installer_generateKey();
$ramVar_authSalt       = ramFn_installer_generateKey();
$ramVar_secureAuthSalt = ramFn_installer_generateKey();
$ramVar_loggedInSalt   = ramFn_installer_generateKey();
$ramVar_nonceSalt      = ramFn_installer_generateKey();

// Template substitution (using string interpolation approach)
$ramVar_generatedDate  = date('Y-m-d H:i:s');
$ramVar_dbPassEsc      = addslashes($ramVar_dbPass);

// ── Write ramayan-config.php ──────────────────────────────────────────────────
$ramVar_configContent = <<<PHP
<?php
/**
 * Ramayan CMS — Configuration File
 * finggu.com | Author: sudarshanpjadhav
 * Generated by Swayamvar Installer on: {$ramVar_generatedDate}
 *
 * DO NOT share this file. Keep it out of version control.
 */

declare(strict_types=1);

// ─── Database ─────────────────────────────────────────────────────────────────
define('RAM_DB_HOST',     '{$ramVar_dbHost}');
define('RAM_DB_NAME',     '{$ramVar_dbName}');
define('RAM_DB_USER',     '{$ramVar_dbUser}');
define('RAM_DB_PASSWORD', '{$ramVar_dbPassEsc}');
define('RAM_DB_CHARSET',  'utf8mb4');
define('RAM_DB_PREFIX',   '{$ramVar_dbPrefix}');

// ─── Site ─────────────────────────────────────────────────────────────────────
define('RAM_URL',      '{$ramVar_siteUrl}');
define('RAM_SITE_URL', '{$ramVar_siteUrl}');

// ─── Security Keys ────────────────────────────────────────────────────────────
define('RAM_AUTH_KEY',         '{$ramVar_authKey}');
define('RAM_SECURE_AUTH_KEY',  '{$ramVar_secureAuthKey}');
define('RAM_LOGGED_IN_KEY',    '{$ramVar_loggedInKey}');
define('RAM_NONCE_KEY',        '{$ramVar_nonceKey}');
define('RAM_AUTH_SALT',        '{$ramVar_authSalt}');
define('RAM_SECURE_AUTH_SALT', '{$ramVar_secureAuthSalt}');
define('RAM_LOGGED_IN_SALT',   '{$ramVar_loggedInSalt}');
define('RAM_NONCE_SALT',       '{$ramVar_nonceSalt}');

// ─── Paths ────────────────────────────────────────────────────────────────────
define('RAM_CONTENT_PATH', RAM_PATH . '/vaanar');
define('RAM_THEME_PATH',   RAM_PATH . '/lanka');
define('RAM_UPLOAD_PATH',  RAM_PATH . '/uploads');
define('RAM_CACHE_PATH',   RAM_PATH . '/cache');
define('RAM_ADMIN_PATH',   RAM_PATH . '/ayodhya');
define('RAM_LOG_PATH',     RAM_PATH . '/logs');

// URL equivalents
define('RAM_CONTENT_URL', RAM_URL . '/vaanar');
define('RAM_THEME_URL',   RAM_URL . '/lanka');
define('RAM_UPLOAD_URL',  RAM_URL . '/uploads');
define('RAM_ADMIN_URL',   RAM_URL . '/ayodhya');

// ─── Cache ────────────────────────────────────────────────────────────────────
define('RAM_CACHE_DRIVER', 'file');
define('RAM_CACHE_TTL',    3600);

// ─── API ──────────────────────────────────────────────────────────────────────
define('RAM_API_VERSION', 'v1');
define('RAM_API_URL',     RAM_URL . '/api/v1');

// ─── Active Theme ─────────────────────────────────────────────────────────────
define('RAM_ACTIVE_THEME', 'ram-default');

// ─── Debug ────────────────────────────────────────────────────────────────────
define('RAM_DEBUG',     false);
define('RAM_DEBUG_LOG', false);

if (RAM_DEBUG) {
    error_reporting(E_ALL);
    ini_set('display_errors', '1');
} else {
    error_reporting(0);
    ini_set('display_errors', '0');
}
PHP;

// No further substitution needed as heredoc handled it.

if (file_put_contents($ramVar_configFile, $ramVar_configContent) === false) {
    ramFn_installer_showError(['Cannot write ramayan-config.php. Check folder permissions.']);
    exit;
}

// ── Run migrations ────────────────────────────────────────────────────────────
try {
    // Bootstrap enough to run migrations
    define('RAM_PATH',       $ramVar_root);
    define('RAM_VERSION',    '1.0.0-alpha');
    define('RAM_DB_PREFIX',  $ramVar_dbPrefix);
    define('RAM_DEBUG',      false);

    require_once $ramVar_root . '/ram/bootstrap/RamLoader.php';
    require_once $ramVar_root . '/global-helpers.php';

    \Ram\Database\PatalDB::ramFn_connect([
        'host'     => $ramVar_dbHost,
        'dbname'   => $ramVar_dbName,
        'user'     => $ramVar_dbUser,
        'password' => $ramVar_dbPass,
        'charset'  => 'utf8mb4',
        'prefix'   => $ramVar_dbPrefix,
    ]);

    \Ram\Database\PatalSchema::ramFn_migrate();

} catch (Throwable $ramVar_e) {
    // Rollback: remove config file so installer can be re-run
    @unlink($ramVar_configFile);
    ramFn_installer_showError(['Migration failed: ' . $ramVar_e->getMessage()]);
    exit;
}

// ── Seed default options ──────────────────────────────────────────────────────
$ramVar_defaultOptions = [
    ['site_name',      $ramVar_siteName,   'yes'],
    ['site_url',       $ramVar_siteUrl,    'yes'],
    ['admin_email',    $ramVar_adminEmail, 'yes'],
    ['active_plugins', '[]',               'yes'],
    ['active_theme',   'ram-default',      'yes'],
    ['ram_version',    '1.0.0-alpha',      'yes'],
    ['date_format',    'd/m/Y',            'yes'],
    ['time_format',    'H:i',              'yes'],
    ['timezone',       'Asia/Kolkata',     'yes'],
    ['posts_per_page', '10',               'yes'],
    ['installed_at',   date('Y-m-d H:i:s'), 'yes'],
];

foreach ($ramVar_defaultOptions as [$ramVar_key, $ramVar_val, $ramVar_auto]) {
    $ramVar_pdo->prepare(
        "INSERT IGNORE INTO `{$ramVar_dbPrefix}options` (option_name, option_value, autoload) VALUES (?, ?, ?)"
    )->execute([$ramVar_key, $ramVar_val, $ramVar_auto]);
}

// ── Create admin user ─────────────────────────────────────────────────────────
$ramVar_passwordHash = password_hash($ramVar_adminPass, PASSWORD_BCRYPT, ['cost' => 12]);
$ramVar_displayName  = ucfirst($ramVar_adminUser);

$ramVar_stmt = $ramVar_pdo->prepare(
    "INSERT INTO `{$ramVar_dbPrefix}users`
     (username, email, password_hash, display_name, role, status, registered_at)
     VALUES (?, ?, ?, ?, 'admin', 'active', NOW())"
);
$ramVar_stmt->execute([$ramVar_adminUser, $ramVar_adminEmail, $ramVar_passwordHash, $ramVar_displayName]);

// ── Create required directories ───────────────────────────────────────────────
$ramVar_dirs = [
    $ramVar_root . '/uploads',
    $ramVar_root . '/uploads/images',
    $ramVar_root . '/cache',
    $ramVar_root . '/logs',
    $ramVar_root . '/vaanar',
    $ramVar_root . '/lanka',
];

foreach ($ramVar_dirs as $ramVar_dir) {
    if (!is_dir($ramVar_dir)) {
        @mkdir($ramVar_dir, 0755, true);
    }
    // Protect directories from direct access
    $ramVar_ht = $ramVar_dir . '/.htaccess';
    if (!file_exists($ramVar_ht) && in_array($ramVar_dir, [
        $ramVar_root . '/cache',
        $ramVar_root . '/logs',
    ], true)) {
        @file_put_contents($ramVar_ht, "Deny from all\n");
    }
}

// ── Seed sample content ────────────────────────────────────────────────────────
$ramVar_pdo->prepare(
    "INSERT INTO `{$ramVar_dbPrefix}posts`
     (author_id, title, slug, content, excerpt, status, post_type, published_at)
     VALUES (1, ?, ?, ?, ?, 'publish', 'post', NOW())"
)->execute([
    'Welcome to Ramayan CMS',
    'welcome-to-ramayan-cms',
    '<p>Congratulations! Your Ramayan CMS installation is complete. This is your first post. Edit or delete it, then start writing!</p>',
    'Congratulations! Your Ramayan CMS installation is complete.',
]);

$ramVar_pdo->prepare(
    "INSERT INTO `{$ramVar_dbPrefix}posts`
     (author_id, title, slug, content, excerpt, status, post_type, published_at)
     VALUES (1, ?, ?, ?, ?, 'publish', 'page', NOW())"
)->execute([
    'About',
    'about',
    '<p>This is an example about page. Edit it to tell visitors about your website.</p>',
    'An example about page.',
]);

// ── Done — show success screen ─────────────────────────────────────────────────
?>
